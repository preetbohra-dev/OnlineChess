// The service worker is generated at start-up: it lists every public file and carries a version
// hash of their contents, so each deploy changes /sw.js byte for byte and browsers update.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

function listFiles(dir, base = dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(full, base));
    else if (entry.isFile()) out.push(path.relative(base, full).split(path.sep).join('/'));
  }
  return out.sort();
}

// The worker itself. VERSION and ASSETS are prepended by buildServiceWorker().
const WORKER = `
const CACHE = 'oc-' + VERSION;

// Install: cache the whole app (about 4 MB) so it works offline. If any file fails, the install
// fails as a whole (the old version stays) and the half-filled cache is dropped. Every file is
// fetched with cache: 'reload': the browser may still hold an older copy (the CDN in front of the
// server tells browsers to keep files for hours), and a new version must never cache old files.
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS.map((url) => new Request(url, { cache: 'reload' }))))
    .catch((err) => caches.delete(CACHE).then(() => { throw err; })));
});

// Activate: drop older versions and take control of open pages.
self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('oc-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// A page asks a waiting new version to take over (the "update ready" banner).
self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') self.skipWaiting();
});

// Daily-puzzle reminders: show the notification; a tap opens (or focuses) the daily puzzle.
self.addEventListener('push', (event) => {
  let data = {};
  try { data = event.data ? event.data.json() : {}; } catch { data = {}; }
  const title = typeof data.title === 'string' ? data.title.slice(0, 80) : 'OnlineChess';
  const body = typeof data.body === 'string' ? data.body.slice(0, 200) : 'Your daily puzzle is waiting.';
  event.waitUntil(self.registration.showNotification(title, { body, icon: '/icons/icon-192.png', badge: '/icons/icon-192.png', tag: 'daily', data: { url: '/#/daily' } }));
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  event.waitUntil(self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((windows) => {
    const open = windows.find((w) => new URL(w.url).origin === self.location.origin);
    if (open) return open.navigate('/#/daily').then((w) => (w || open).focus());
    return self.clients.openWindow('/#/daily');
  }));
});

// Cache first for the app's own files, from this version's cache only (never a newer one still
// waiting, so old and new files never mix). The API and online play always go to the network.
self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (url.pathname === '/sw.js' || url.pathname === '/ws' || url.pathname.startsWith('/api/')) return;
  event.respondWith(caches.open(CACHE).then(async (cache) => {
    const hit = await cache.match(request, { ignoreSearch: true });
    if (hit) return hit;
    try {
      return await fetch(request);
    } catch (err) {
      // Offline: any page navigation gets the app (it routes by #hash).
      if (request.mode === 'navigate') return (await cache.match('/')) || Response.error();
      throw err;
    }
  }));
});
`;

export function buildServiceWorker(publicDir) {
  const files = listFiles(publicDir);
  const hash = crypto.createHash('sha256');
  hash.update(WORKER); // a change to the worker itself is a new version too
  for (const f of files) hash.update(f).update(fs.readFileSync(path.join(publicDir, f)));
  const version = hash.digest('hex').slice(0, 12);
  const assets = ['/', ...files.filter((f) => f !== 'index.html').map((f) => `/${f}`)];
  const body = `// OnlineChess service worker (generated by server/service-worker.js)\nconst VERSION = ${JSON.stringify(version)};\nconst ASSETS = ${JSON.stringify(assets)};\n${WORKER}`;
  return { version, assets, body };
}
